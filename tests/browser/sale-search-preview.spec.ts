test('código exato, nomes independentes, teclado e contexto da unidade',async({page})=>{
  const {state}=await setup(page);
  await page.getByRole('button',{name:'+ NOVA VENDA',exact:true}).click();
  const customer=page.getByRole('combobox',{name:'Cliente',exact:true});
  await customer.fill('350'); await expect(page.getByRole('listbox').getByRole('option')).toHaveCount(1);
  await expect(page.getByRole('listbox').getByRole('option')).toContainText('Cristal Centro'); await customer.press('Enter');
  await expect(customer).toHaveValue(/350 - Cristal Centro/);
  const branch=page.getByRole('combobox',{name:'Unidade / Filial',exact:true});
  await branch.selectOption(uuid(1350));
  await customer.fill('crístal'); await expect(page.getByRole('listbox').getByRole('option')).toHaveCount(2);
  await customer.press('Enter'); await expect(branch).toHaveValue(uuid(1350));
  await customer.press('ArrowDown'); await customer.press('ArrowDown'); await customer.press('Enter');
  await expect(customer).toHaveValue(/351 - Cristal Norte/);
  await expect(branch).toHaveValue(uuid(1351));
  await customer.fill('Cristal');
  await page.getByRole('listbox').getByRole('option').filter({hasText:'Cristal Centro'}).click();
  await branch.selectOption(uuid(1350));
  await expect(customer).toHaveValue(/350 - Cristal Centro/);
  await customer.fill('inexistente'); await expect(page.getByText('Nenhum resultado encontrado.')).toBeVisible();
  await customer.press('Escape'); await expect(customer).toHaveAttribute('aria-expanded','false');
  expect(state.writes).toEqual([]);
});

